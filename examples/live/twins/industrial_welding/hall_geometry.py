"""One geometric source for physical parts, seam frames, validation and map export.

All workpieces are rigid, clamped fixtures. Local +Z is up; quaternions XYZW.
No object pose is changed by the demonstration routines.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation as R

ROOT = Path(__file__).resolve().parent
STEEL = (0.54, 0.56, 0.57)
WEB = (0.48, 0.51, 0.53)
CUT = (0.68, 0.70, 0.71)
BLUE = (0.055, 0.18, 0.24)
YELLOW = (0.90, 0.62, 0.07)


def load_config():
    return json.loads((ROOT / "config.json").read_text())


def panel_configs(config):
    """All large panels; retain the original parallel/grid config keys."""
    return [config["parallel"], config["grid"], *config.get("additional_panels", [])]


def transform(points, pose):
    p = np.asarray(points, float)
    return R.from_quat(pose[3:]).apply(p) + np.asarray(pose[:3])


def prism(points2, z0, z1):
    """Convex polygon extrusion. Faces are generated by the hull, never a bbox proxy."""
    from scipy.spatial import ConvexHull

    v = np.array([[x, y, z] for z in (z0, z1) for x, y in points2], float)
    f = ConvexHull(v).simplices
    # Consistently outward triangles (ConvexHull simplices do not promise winding).
    mid = v.mean(0)
    for tri in f:
        a, b, c = v[tri]
        if np.dot(np.cross(b - a, c - a), (a + b + c) / 3 - mid) < 0:
            tri[1], tri[2] = tri[2], tri[1]
    return v.tolist(), f.tolist()


class Hall:
    def __init__(self, config=None):
        self.config = config or load_config()
        self.objects = {}
        self.seams = []
        self._build()
        names = [p["name"] for o in self.objects.values() for p in o["parts"]]
        assert len(names) == len(set(names)), "Part names must be globally unique"

    def object(self, name, pose, kind, **meta):
        o = {"id": name, "kind": kind, "pose": list(pose), "parts": [], **meta}
        self.objects[name] = o
        return o

    def box(self, o, name, center, size, color=STEEL, quat=(0, 0, 0, 1), collision=True, role="steel"):
        assert min(size) > 0, (name, size)
        o["parts"].append(
            {
                "name": f"{o['id']}_{name}",
                "type": "box",
                "center": list(center),
                "size": list(size),
                "quat": list(quat),
                "color": list(color),
                "collision": collision,
                "role": role,
            }
        )

    def mesh(self, o, name, vertices, faces, color=WEB, role="steel"):
        o["parts"].append(
            {
                "name": f"{o['id']}_{name}",
                "type": "convex",
                "vertices": vertices,
                "faces": faces,
                "color": list(color),
                "collision": True,
                "role": role,
            }
        )

    def seam(self, o, label, points, n1, n2, access="candidate", category="fillet"):
        points = np.asarray(points, float)
        dist = np.r_[0, np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))]
        spacing = self.config["welding"]["sample_spacing_m"]
        s = np.linspace(0, dist[-1], max(3, int(np.ceil(dist[-1] / spacing)) + 1))
        p = np.stack([np.interp(s, dist, points[:, i]) for i in range(3)], axis=1)
        n1 = np.broadcast_to(np.asarray(n1, float), (len(points), 3))
        n2 = np.broadcast_to(np.asarray(n2, float), (len(points), 3))
        ns = []
        for normals in (n1, n2):
            v = np.stack([np.interp(s, dist, normals[:, i]) for i in range(3)], axis=1)
            ns.append(v / np.linalg.norm(v, axis=1)[:, None])
        tangent = np.gradient(p, axis=0)
        tangent /= np.linalg.norm(tangent, axis=1)[:, None]
        z = -(ns[0] + ns[1])
        z /= np.linalg.norm(z, axis=1)[:, None]
        angle = next((c.get("travel_angle_deg", 0) for c in self.config["stations"] if c["id"] == o["id"]), 0)
        z = z * np.cos(np.deg2rad(angle)) + tangent * np.sin(np.deg2rad(angle))
        z /= np.linalg.norm(z, axis=1)[:, None]
        x = tangent - (tangent * z).sum(1)[:, None] * z
        x /= np.linalg.norm(x, axis=1)[:, None]
        y = np.cross(z, x)
        quat = R.from_matrix(np.stack([x, y, z], axis=2)).as_quat()
        target = p - z * self.config["welding"]["tcp_standoff_m"]
        roll = next(
            (
                c.get("torch_roll_deg", 0)
                for c in [*self.config["stations"], *panel_configs(self.config)]
                if c["id"] == o["id"]
            ),
            0,
        )
        if roll:
            quat = (R.from_quat(quat) * R.from_euler("z", roll, degrees=True)).as_quat()
        segment_length = next(
            (
                c.get("segment_length_m", self.config["welding"]["segment_length_m"])
                for c in [*self.config["stations"], *panel_configs(self.config)]
                if c["id"] == o["id"]
            ),
            self.config["welding"]["segment_length_m"],
        )
        segments = []
        starts = list(range(0, len(p) - 1, max(1, int(segment_length / spacing))))
        for i, a in enumerate(starts):
            b = min(a + max(1, int(segment_length / spacing)), len(p) - 1)
            profile = next(
                (
                    c.get("segment_torch_roll_deg", {})
                    for c in [*self.config["stations"], *panel_configs(self.config)]
                    if c["id"] == o["id"]
                ),
                {},
            )
            extra = profile.get(f"{label}.{i:02d}", roll) - roll
            angle_profile = next(
                (c.get("segment_travel_angle_deg", {}) for c in self.config["stations"] if c["id"] == o["id"]), {}
            )
            segment_angle = angle_profile.get(f"{label}.{i:02d}", angle)
            segment_quat = (
                R.from_quat(quat[a : b + 1])
                * R.from_euler("z", -roll, degrees=True)
                * R.from_euler("y", segment_angle - angle, degrees=True)
                * R.from_euler("z", roll + extra, degrees=True)
            ).as_quat()
            segment_axis = R.from_quat(segment_quat).apply(np.tile([0, 0, 1], (len(segment_quat), 1)))
            segment_target = p[a : b + 1] - segment_axis * self.config["welding"]["tcp_standoff_m"]
            segments.append(
                {
                    "local_tcp_quat_xyzw": segment_quat.tolist(),
                    "local_tcp_points_m": segment_target.tolist(),
                    "travel_angle_deg": float(segment_angle),
                    "torch_roll_deg": float(roll + extra),
                    "id": f"{o['id']}.{label}.{i:02d}",
                    "sample_start": a,
                    "sample_end": b,
                    "length_m": float(s[b] - s[a]),
                    "requires_retract_before_reposition": True,
                }
            )
        self.seams.append(
            {
                "id": f"{o['id']}.{label}",
                "workpiece": o["id"],
                "family": o["kind"],
                "category": category,
                "local_frame": o["id"],
                "local_points_m": p.tolist(),
                "local_tangent": tangent.tolist(),
                "local_surface_normals": np.stack(ns, 1).tolist(),
                "local_tcp_points_m": target.tolist(),
                "local_tcp_quat_xyzw": quat.tolist(),
                "length_m": float(s[-1]),
                "segments": segments,
                "access": access,
                "completion": 0.0,
            }
        )

    def support(self, o, top, sx=1.24, sy=0.74):
        self.box(o, "table_top", (0, 0, top - 0.025), (sx, sy, 0.05), BLUE, role="support")
        for x in (-sx / 2 + 0.07, sx / 2 - 0.07):
            for y in (-sy / 2 + 0.07, sy / 2 - 0.07):
                self.box(o, f"leg_{x}_{y}", (x, y, (top - 0.05) / 2), (0.065, 0.065, top - 0.05), BLUE, role="support")
                self.box(o, f"foot_{x}_{y}", (x, y, 0.012), (0.14, 0.12, 0.024), BLUE, role="support")

    def butt_pair(self, o, c):
        """Two real plates with mating V edges, backed and clamped on a cradle."""
        from scipy.spatial import ConvexHull

        h, t = c["table_height_m"], c["plate_thickness_m"]
        length, width = c["pair_size_m"]
        gap, depth = c["root_gap_m"], c["groove_depth_m"]
        angle = c["incline_deg"]
        included = c["groove_included_angle_deg"]
        assert 0 <= angle < 90 and 0 < depth < t and 0 <= gap <= 0.002
        bevel = depth * np.tan(np.deg2rad(included / 2))
        rot = R.from_euler("x", angle, degrees=True)
        backing = c["backing_thickness_m"]
        origin = np.array([0, 0, h + backing + c["fixture_lift_m"] + width / 2 * np.sin(np.deg2rad(angle))])
        self.box(o, "fixture_platen", (0, 0, h + backing / 2), (1.10, 0.64, backing), BLUE, role="fixture")
        for side, label in ((-1, "negative"), (1, "positive")):
            section = [
                [side * gap / 2, 0],
                [side * width / 2, 0],
                [side * width / 2, t],
                [side * (gap / 2 + bevel), t],
                [side * gap / 2, t - depth],
            ]
            v, faces = prism(section, -length / 2, length / 2)
            # prism axes (cross-section v,w, extrusion u) -> plate axes (u,v,w).
            vertices = rot.apply(np.asarray(v)[:, [2, 0, 1]]) + origin
            color = c.get("plate_colors_rgb", [[0.42, 0.45, 0.48], [0.49, 0.52, 0.54]])[int(side > 0)]
            self.mesh(o, "plate_" + label, vertices.tolist(), faces, color)
            band = c["preparation_band_width_m"]
            center = rot.apply([0, side * (gap / 2 + bevel + band / 2), t + 0.0001]) + origin
            self.box(
                o,
                "prepared_" + label,
                center,
                (length - 0.10, band, 0.0002),
                c.get("prepared_color_rgb", [0.78, 0.80, 0.81]),
                quat=rot.as_quat(),
                collision=False,
                role="machined",
            )
            for x in (-length / 2 + 0.04, length / 2 - 0.04):
                center = rot.apply([x, side * (width / 2 - 0.04), t + 0.012]) + origin
                self.box(
                    o, f"clamp_{label}_{x}", center, (0.055, 0.05, 0.024), YELLOW, quat=rot.as_quat(), role="fixture"
                )
        if angle:
            half_y = width / 2 * np.cos(np.deg2rad(angle)) - 0.01
            for x in (-length / 2 + 0.04, length / 2 - 0.04):
                vertices = [
                    [xx, yy, zz]
                    for xx in (x - 0.03, x + 0.03)
                    for yy in (-half_y, half_y)
                    for zz in (h + backing, origin[2] + np.tan(np.deg2rad(angle)) * yy)
                ]
                self.mesh(
                    o, f"incline_cradle_{x}", vertices, ConvexHull(vertices).simplices.tolist(), BLUE, role="fixture"
                )
        points = rot.apply([[-length / 2 + 0.07, 0, t - depth], [length / 2 - 0.07, 0, t - depth]]) + origin
        # Actual outward V-face normals; their bisector is the plate normal.
        n1, n2 = rot.apply([[0, depth, bevel], [0, -depth, bevel]])
        self.seam(o, "butt_center", points, n1, n2, category="single_V_butt")
        joint = {
            "plate_parts": [o["id"] + "_plate_negative", o["id"] + "_plate_positive"],
            "root_gap_m": gap,
            "groove_depth_m": depth,
            "root_land_m": t - depth,
            "groove_included_angle_deg": included,
            "groove_top_opening_m": gap + 2 * bevel,
            "incline_from_horizontal_deg": angle,
            "incline_axis": "workpiece +X (seam direction)",
            "root_centerline": "mid-gap at groove bottom, not a completed weld bead",
            "preparation_band": "visual ground-metal finish only; no added collision or weld completion",
        }
        o["joint_geometry"] = joint
        self.seams[-1]["joint_geometry"] = joint

    def station(self, c):
        h, t, r = c["table_height_m"], c["plate_thickness_m"], c["rib_height_m"]
        q = R.from_euler("z", c["yaw_deg"], degrees=True).as_quat().tolist()
        o = self.object(
            c["id"],
            [*c["xy"], 0, *q],
            c["kind"],
            table_height_m=h,
            plate_thickness_m=t,
            fixture="clamped static; no weld process forces",
            zone="A",
        )
        self.support(o, h)
        if c["kind"] == "butt_plate":
            self.butt_pair(o, c)
            return
        self.box(o, "base", (0, 0, h + t / 2), (1.10, 0.60, t))
        z = h + t
        kind = c["kind"]
        if kind == "t_joint":
            self.box(o, "web", (0, 0, z + r / 2), (0.90, t, r), WEB)
            self.seam(o, "root_front", [[-0.42, -t / 2, z], [0.42, -t / 2, z]], [0, 0, 1], [0, -1, 0])
        elif kind == "vertical_corner":
            # L sheets meet at a real plate edge, not at intersecting solid midplanes.
            self.box(o, "back", (0, 0.15, z + r / 2), (0.58, t, r), WEB)
            self.box(o, "return", (-0.29 + t / 2, -0.03, z + r / 2), (t, 0.36 - t, r), WEB)
            self.seam(
                o,
                "vertical_up",
                [[-0.29 + t, 0.15 - t / 2, z + 0.03], [-0.29 + t, 0.15 - t / 2, z + r - 0.03]],
                [1, 0, 0],
                [0, -1, 0],
                category="vertical_fillet",
            )
        elif kind == "horizontal_lap":
            seam_z = c.get("seam_height_m", 0.85)
            overlap = c.get("lap_overlap_m", 0.06)
            low = seam_z - z
            high = z + r - seam_z + overlap
            # Front lower sheet overlaps the rear upper sheet. The lower
            # sheet's finite-thickness top edge makes a visible horizontal step.
            self.box(o, "lap_lower", (0, -t, z + low / 2), (0.90, t, low), WEB)
            self.box(o, "lap_upper", (0, 0, seam_z - overlap + high / 2), (0.90, t, high), STEEL)
            for x in (-0.47, 0.47):
                self.box(o, f"post_{x}", (x, 0.07, z + r / 2), (0.035, 0.07, r), BLUE, role="fixture")
            # A thin surface-finish patch represents preparation by grinding,
            # not a weld bead, collision body, or completed-weld state.
            self.box(
                o,
                "lap_prepared_face",
                (0, -t / 2 - 0.0001, seam_z + 0.013),
                (0.84, 0.0002, 0.026),
                CUT,
                collision=False,
                role="machined",
            )
            self.seam(
                o,
                "lap_horizontal",
                [[-0.40, -t / 2, seam_z], [0.40, -t / 2, seam_z]],
                [0, -1, 0],
                [0, 0, 1],
                category="horizontal_lap_fillet",
            )
        elif kind == "inclined":
            a = np.deg2rad(c.get("incline_deg", 22))
            rot = R.from_euler("y", -a)
            q2 = rot.as_quat()
            center = np.array([0, 0, z + c.get("incline_lift_m", 0.20)])
            self.box(o, "inclined_base", center, (0.94, 0.48, t), quat=q2)
            rib = rot.apply([0, 0, t / 2 + r / 2]) + center
            self.box(o, "inclined_web", rib, (0.82, t, r), WEB, quat=q2)
            for x in (-0.32, 0.32):
                vertices = [
                    [xx, yy, zz]
                    for level in (0, 1)
                    for xx in (x - 0.03, x + 0.03)
                    for yy in (0.085, 0.235)
                    for zz in [h + t if level == 0 else center[2] + np.tan(a) * xx - t / (2 * np.cos(a))]
                ]
                from scipy.spatial import ConvexHull

                self.mesh(o, f"cradle_{x}", vertices, ConvexHull(vertices).simplices.tolist(), BLUE, role="fixture")
            pts = rot.apply([[-0.38, -t / 2, t / 2], [0.38, -t / 2, t / 2]]) + center
            self.seam(o, "inclined_root", pts, rot.apply([0, 0, 1]), rot.apply([0, -1, 0]))
        elif kind == "s_curve":
            length = c.get("curve_length_m", 1.0)
            amp = c.get("curve_amplitude_m", 0.10)
            x = np.linspace(-length / 2, length / 2, 81)
            y = amp * np.sin(2 * np.pi * x / length)
            dy = amp * 2 * np.pi / length * np.cos(2 * np.pi * x / length)
            side = np.column_stack([dy, -np.ones(len(x))])
            side /= np.linalg.norm(side, axis=1)[:, None]
            center = np.column_stack([x, y])
            front = center + side * t / 2
            back = center - side * t / 2
            # Mitered adjacent convex strips share faces exactly; no overlapping boxes.
            for i in range(len(x) - 1):
                v, f = prism([front[i], front[i + 1], back[i + 1], back[i]], z, z + r)
                self.mesh(o, f"curved_web_{i:02d}", v, f)
            pts = np.column_stack([front, np.full(len(x), z)])
            self.seam(
                o, "open_S_root", pts, [0, 0, 1], np.column_stack([side, np.zeros(len(x))]), category="open_S_fillet"
            )
        elif kind == "open_gusset_bracket":
            # L return and back plate: front and right stay open for the torch.
            bx, by = c.get("bracket_size_m", [0.82, 0.40])
            yback = 0.16
            front = yback - by
            self.box(o, "bracket_back", (0, yback, z + r / 2), (bx, t, r), WEB)
            for x in (-bx / 2 + t / 2,):
                self.box(
                    o, f"bracket_return_{x}", (x, (front + yback - t / 2) / 2, z + r / 2), (t, by - t / 2, r), STEEL
                )
            gy = yback - t / 2
            gx = -bx / 2 + t
            gfront = -0.14
            gh = min(0.26, r - 0.04)
            tip = 0.19
            v = [[x, y, zz] for y in (gfront - t / 2, gfront + t / 2) for x, zz in ((gx, z), (tip, z), (gx, z + gh))]
            from scipy.spatial import ConvexHull

            self.mesh(o, "exposed_triangular_gusset", v, ConvexHull(v).simplices.tolist(), STEEL)
            for label, xa, xb in (("left", -bx / 2 + t + 0.02, 0.02), ("right", 0.04, bx / 2 - 0.02)):
                self.seam(o, f"open_back_root_{label}", [[xa, gy, z], [xb, gy, z]], [0, 0, 1], [0, -1, 0])
            self.seam(
                o,
                "gusset_foot",
                [[gx + 0.02, gfront - t / 2, z], [tip - 0.02, gfront - t / 2, z]],
                [0, 0, 1],
                [0, -1, 0],
                category="gusset_fillet",
            )
            for sign in (-1, 1):
                y = gfront + sign * t / 2
                self.seam(
                    o,
                    f"gusset_wall_{sign}",
                    [[gx, y, z + 0.02], [gx, y, z + gh - 0.02]],
                    [1, 0, 0],
                    [0, sign, 0],
                    category="gusset_wall_fillet",
                    access="requires_corner_process_planning",
                )
            self.seam(
                o,
                "open_vertical_corner",
                [[-bx / 2 + t, gy, z + 0.02], [-bx / 2 + t, gy, z + r - 0.02]],
                [1, 0, 0],
                [0, -1, 0],
                category="vertical_fillet",
            )
        # Four clamp shoes stay outside the active roots.
        for x in (-0.50, 0.50):
            for y in (-0.26, 0.26):
                self.box(o, f"clamp_{x}_{y}", (x, y, z + 0.012), (0.055, 0.05, 0.024), YELLOW, role="fixture")

    def panel(self, c, grid=False):
        sx, sy = c["size_m"]
        t = c["plate_thickness_m"]
        r = c["rib_height_m"]
        o = self.object(
            c["id"],
            [*c["xy"], 0, 0, 0, 0, 1],
            "grid_panel" if grid else "parallel_panel",
            zone="B",
            table_height_m=0.0,
            plate_thickness_m=t,
            standing_surface_m=t,
            entry_width_m=c.get("cross_lane_width_m", c.get("entry_width_m")),
            access_policy="cross lane and perimeter only; ribs are obstacles, no step-over",
        )
        self.box(o, "deck", (0, 0, t / 2), (sx, sy, t))

        def rib(label, a, b, along):
            p = (np.array(a) + np.array(b)) / 2
            d = np.abs(np.array(b) - np.array(a))
            self.box(o, label, (*p, t + r / 2), (d[0] or t, d[1] or t, r), WEB)
            if along == "x":
                for sign in (-1, 1):
                    y = p[1] + sign * t / 2
                    access = "candidate" if abs(p[1]) > 0.8 else "restricted_enclosed_or_obstructed"
                    if grid:
                        exposed = (abs(abs(p[1]) - sy / 2) < 0.02 and sign * p[1] > 0) or (
                            abs(abs(p[1]) - w) < 0.02 and sign * p[1] < 0
                        )
                        access = "candidate_perimeter_or_cross_lane" if exposed else "restricted_closed_cell"
                    self.seam(
                        o, label + f"_side{sign}", [[a[0], y, t], [b[0], y, t]], [0, 0, 1], [0, sign, 0], access=access
                    )
                for x in (a[0], b[0]):
                    self.seam(
                        o,
                        label + f"_end{x}",
                        [[x, p[1] - t / 2, t], [x, p[1] + t / 2, t]],
                        [0, 0, 1],
                        [1 if x == b[0] else -1, 0, 0],
                        category="rib_end",
                    )
            else:
                for sign in (-1, 1):
                    x = p[0] + sign * t / 2
                    exposed = (abs(abs(x) - sx / 2) < 0.03 and sign * p[0] > 0) or (
                        abs(abs(p[0]) - w) < 0.02 and sign * p[0] < 0
                    )
                    self.seam(
                        o,
                        label + f"_side{sign}",
                        [[x, a[1], t], [x, b[1], t]],
                        [0, 0, 1],
                        [sign, 0, 0],
                        access="candidate_perimeter_or_cross_lane" if exposed else "restricted_closed_cell",
                    )

        w = o["entry_width_m"] / 2
        if not grid:
            for i in range(c["rib_count"]):
                y = (i - (c["rib_count"] - 1) / 2) * c["rib_spacing_m"]
                for side, a, b in (("west", -sx / 2 + 0.04, -w), ("east", w, sx / 2 - 0.04)):
                    rib(f"parallel_{i}_{side}", (a, y), (b, y), "x")
        else:
            # Longitudinal ribs are continuous within each half. Transverse plates
            # butt with 1 mm assembly gaps at their faces: no material overlap.
            ys = sorted(set([-sy / 2 + t / 2, -w, w, sy / 2 - t / 2] + c["longitudinal_rib_y_m"]))
            xs = sorted(set([-sx / 2 + t / 2, -w, w, sx / 2 - t / 2] + c["transverse_rib_x_m"]))
            for i, y in enumerate(ys):
                for side, a, b in (
                    ("west", -sx / 2 + t + 0.001, -w - t / 2 - 0.001),
                    ("east", w + t / 2 + 0.001, sx / 2 - t - 0.001),
                ):
                    rib(f"long_{i}_{side}", (a, y), (b, y), "x")
            for i, x in enumerate(xs):
                intervals = [
                    (a + t / 2 + 0.001, b - t / 2 - 0.001)
                    for a, b in itertools.pairwise(ys)
                    if not (a <= -w and b >= w)
                ]
                for j, (a, b) in enumerate(intervals):
                    rib(f"trans_{i}_{j}", (x, a), (x, b), "y")
                    # The intersection fillet is the 1 mm butt gap at the web face.
                    yy = a - 0.001 if j % 2 == 1 else None
                    if yy is not None:
                        self.seam(
                            o,
                            f"intersection_{i}_{j}",
                            [[x - t / 2, yy, t + 0.02], [x - t / 2, yy, t + r - 0.02]],
                            [-1, 0, 0],
                            [0, 1 if j == 1 else -1, 0],
                            category="intersection_fillet",
                        )
        # Smooth, load-bearing 0.4 m wedges along cross-lane entrances.
        length = 0.40
        for sign in (-1, 1):
            # Actual wedge prism built directly, top ramps 0 -> deck t.
            yy = sign * sy / 2
            verts = [
                [-w, yy, 0],
                [w, yy, 0],
                [-w, yy + sign * length, 0],
                [w, yy + sign * length, 0],
                [-w, yy, t],
                [w, yy, t],
            ]
            from scipy.spatial import ConvexHull

            self.mesh(o, f"entry_ramp_{sign}", verts, ConvexHull(verts).simplices.tolist(), STEEL, role="ramp")
        if grid:
            # Side entrances reach the same cross lane; floor to deck ramp.
            for sign in (-1, 1):
                xx = sign * sx / 2
                verts = [
                    [xx, -w, 0],
                    [xx, w, 0],
                    [xx + sign * 0.4, -w, 0],
                    [xx + sign * 0.4, w, 0],
                    [xx, -w, t],
                    [xx, w, t],
                ]
                from scipy.spatial import ConvexHull

                self.mesh(o, f"side_ramp_{sign}", verts, ConvexHull(verts).simplices.tolist(), STEEL, role="ramp")

    def _build(self):
        c = self.config
        o = self.object("hall", [0, 0, 0, 0, 0, 0, 1], "building", zone="hall")
        sx, sy = c["hall"]["size_m"]
        ceiling = c["hall"]["ceiling_m"]
        self.box(o, "floor", (0, 0, -0.05), (sx, sy, 0.10), (0.31, 0.33, 0.32), role="floor")
        for x in np.linspace(-sx / 2 + 0.25, sx / 2 - 0.25, 5):
            for y in (-sy / 2 + 0.25, sy / 2 - 0.25):
                self.box(
                    o,
                    f"column_{x}_{y}",
                    (x, y, ceiling / 2),
                    (0.20, 0.20, ceiling),
                    (0.20, 0.25, 0.27),
                    role="building",
                )
                self.box(o, f"column_guard_{x}_{y}", (x, y, 0.35), (0.24, 0.24, 0.70), YELLOW, role="building")
            self.box(
                o,
                f"roof_beam_{x}",
                (x, 0, ceiling - 0.15),
                (0.18, sy - 0.50, 0.24),
                (0.23, 0.29, 0.30),
                role="building",
            )
        # Two back walls + high clerestory glazing; south/west are cut away for inspection.
        self.box(o, "north_wall", (0, sy / 2, 1.5), (sx, 0.10, 3), (0.49, 0.52, 0.50), role="building")
        self.box(o, "east_wall", (sx / 2, 0, 1.5), (0.10, sy, 3), (0.49, 0.52, 0.50), role="building")
        for x in np.arange(-sx / 2 + 2, sx / 2 - 1, 2):
            self.box(
                o,
                f"window_{x}",
                (x, sy / 2 - 0.06, 4.15),
                (1.70, 0.03, 1.65),
                (0.49, 0.66, 0.70),
                collision=False,
                role="window",
            )
        # Floor paint is visual only and cannot lift a foot or influence maps.
        for y in (-c["hall"]["main_aisle_m"] / 2, c["hall"]["main_aisle_m"] / 2):
            self.box(
                o, f"main_line_{y}", (0, y, 0.0005), (sx - 0.9, 0.045, 0.001), YELLOW, collision=False, role="paint"
            )
        for panel in panel_configs(c):
            x, y = panel["xy"]
            dx, dy = np.asarray(panel["size_m"]) + 0.7
            for sign in (-1, 1):
                self.box(
                    o,
                    f"zone_line_{panel['id']}_{sign}",
                    (x, y + sign * dy / 2, 0.0006),
                    (dx, 0.04, 0.001),
                    YELLOW,
                    collision=False,
                    role="paint",
                )
        for s in c["stations"]:
            self.station(s)
        for panel in panel_configs(c):
            self.panel(panel, grid="cross_lane_width_m" in panel)
        for ob in c["obstacles"]:
            x, y = ob["xy"]
            dx, dy, dz = ob["size_m"]
            o = self.object(ob["id"], [x, y, 0, 0, 0, 0, 1], "obstacle")
            if ob["id"] == "steel_rack":
                for xx in (-dx / 2, dx / 2):
                    for yy in (-dy / 2, dy / 2):
                        self.box(o, f"post_{xx}_{yy}", (xx, yy, dz / 2), (0.07, 0.07, dz), BLUE, role="obstacle")
                for zz in (0.10, 0.65, 1.2):
                    self.box(o, f"shelf_{zz}", (0, 0, zz), (dx, dy, 0.04), BLUE, role="obstacle")
                    for yy in (-0.22, 0, 0.22):
                        self.box(
                            o, f"bar_{zz}_{yy}", (0, yy, zz + 0.06), (dx - 0.12, 0.07, 0.08), STEEL, role="obstacle"
                        )
            elif ob["id"] == "plate_stack":
                for i in range(10):
                    self.box(o, f"sheet_{i}", (0, 0, 0.02 + i * 0.02), (dx, dy, 0.015), STEEL, role="obstacle")
            else:
                self.box(o, "body", (0, 0, dz / 2), (dx, dy, dz), BLUE, role="obstacle")
                self.box(
                    o,
                    "door",
                    (0, -dy / 2 - 0.006, dz / 2),
                    (dx * 0.86, 0.012, dz * 0.88),
                    (0.14, 0.30, 0.34),
                    role="obstacle",
                )

    def world_parts(self):
        for o in self.objects.values():
            rot = R.from_quat(o["pose"][3:])
            for p in o["parts"]:
                out = {**p, "object": o["id"]}
                if p["type"] == "box":
                    out["center"] = transform(p["center"], o["pose"]).tolist()
                    out["quat"] = (rot * R.from_quat(p["quat"])).as_quat().tolist()
                else:
                    out["vertices"] = transform(p["vertices"], o["pose"]).tolist()
                yield out

    def world_seams(self, pose_overrides=None):
        out = []
        for s in self.seams:
            pose = (pose_overrides or {}).get(s["workpiece"], self.objects[s["workpiece"]]["pose"])
            rot = R.from_quat(pose[3:])
            p = transform(s["local_points_m"], pose)
            tcp = transform(s["local_tcp_points_m"], pose)
            q = (rot * R.from_quat(s["local_tcp_quat_xyzw"])).as_quat()
            d = self.config["welding"]["approach_distance_m"]
            z = R.from_quat(q).apply(np.tile([0, 0, 1], (len(q), 1)))
            n = np.array(s["local_surface_normals"])
            n = rot.apply(n.reshape(-1, 3)).reshape(n.shape)
            segments = [
                {
                    **seg,
                    "world_tcp_quat_xyzw": (rot * R.from_quat(seg["local_tcp_quat_xyzw"])).as_quat().tolist(),
                    "world_tcp_points_m": transform(seg["local_tcp_points_m"], pose).tolist(),
                }
                for seg in s["segments"]
            ]
            for segment in segments:
                sp = np.asarray(segment["world_tcp_points_m"])
                sq = R.from_quat(segment["world_tcp_quat_xyzw"])
                axes = sq.apply(np.tile([0, 0, 1], (len(sp), 1)))
                segment["approach_point_m"] = (sp[0] - d * axes[0]).tolist()
                segment["exit_point_m"] = (sp[-1] - d * axes[-1]).tolist()
                segment["world_tcp_start_pose_xyzw"] = [*sp[0], *sq.as_quat()[0]]
                segment["world_tcp_end_pose_xyzw"] = [*sp[-1], *sq.as_quat()[-1]]
            out.append(
                {
                    **s,
                    "segments": segments,
                    "world_frame_pose_xyzw": list(pose),
                    "world_points_m": p.tolist(),
                    "world_tangent": rot.apply(s["local_tangent"]).tolist(),
                    "world_surface_normals": n.tolist(),
                    "world_tcp_points_m": tcp.tolist(),
                    "world_tcp_quat_xyzw": q.tolist(),
                    "approach_point_m": (tcp[0] - d * z[0]).tolist(),
                    "exit_point_m": (tcp[-1] - d * z[-1]).tolist(),
                    "seam_height_range_m": [float(p[:, 2].min()), float(p[:, 2].max())],
                    "table_height_m": self.objects[s["workpiece"]].get("table_height_m"),
                }
            )
        return out

    def export(self, pose_overrides=None):
        out = ROOT / "exports"
        out.mkdir(exist_ok=True)
        (out / "scene_geometry.json").write_text(
            json.dumps(
                {
                    "units": "m",
                    "up_axis": "Z",
                    "objects": {
                        key: {**o, "pose": list((pose_overrides or {}).get(key, o["pose"]))}
                        for key, o in self.objects.items()
                    },
                },
                indent=2,
                default=lambda v: v.item(),
            )
        )
        (out / "seams.json").write_text(
            json.dumps(
                {
                    "schema_version": 1,
                    "units": "m",
                    "quaternion_order": "xyzw",
                    "tool_axis": "+Z nozzle outward; +X travel tangent",
                    "map_source": "parametric workpiece geometry",
                    "seams": self.world_seams(pose_overrides),
                },
                indent=2,
            )
        )
        return out
